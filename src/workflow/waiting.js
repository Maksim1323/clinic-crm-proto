'use strict';
// Fixed responses for cases in which free generation is inappropriate.
const WAITING_FALLBACK='Ваше сообщение добавлено в диалог для сотрудника. Точное время ответа мне неизвестно.';
const EMERGENCY_RESPONSE='При сильной боли, затруднении дыхания или угрозе жизни немедленно обратитесь за срочной медицинской помощью; при угрозе жизни вызовите местную экстренную службу. Сообщение также передано сотруднику клиники.';
function emergency(text) {
  return /(задыха|не могу дышать|тяжело дышать|трудно дышать|затруднен.{0,12}дыхан|теряю сознание|потерял.{0,8}сознани|умираю|угроза жизни|сильн.{0,15}кровотеч|сильн.{0,12}бол)/i.test(String(text));
}
function safetyReply(text, reason) {
  if(emergency(text))return EMERGENCY_RESPONSE;
  if(reason && /Медицинский|Несовершеннолетний/.test(reason))return 'Понимаю ваше беспокойство. Я передал сообщение сотруднику, который сможет проверить ситуацию. Я не могу давать медицинские рекомендации.';
  if(reason && /Жалоба|Финансовые/.test(reason))return 'Понимаю, что ситуация неприятная. Сообщение передано сотруднику для рассмотрения.';
  if(reason && /сотрудника/.test(reason))return WAITING_FALLBACK;
  if(reason && /Изменение существующей/.test(reason))return 'Информация передана сотруднику. Я не могу подтвердить изменение записи без проверки.';
  if(/(сколько\s+(?:это\s+)?(?:будет\s+)?стоить|сколько\s+(?:стоит|стоят)|стоимост|цен[аыуеу]|прайс|поч[её]м)/i.test(text))return 'Вопрос о стоимости передан сотруднику. Проверенного прайса у меня нет.';
  if(/(запис|запиш|свободн.{0,20}(?:время|окн)|расписани|слот)/i.test(text))return 'Ваше сообщение передано сотруднику. Я не могу проверить расписание или подтвердить запись.';
  return '';
}
module.exports={WAITING_FALLBACK,EMERGENCY_RESPONSE,emergency,safetyReply};
